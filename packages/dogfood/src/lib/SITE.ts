// THE SITE: every page, in reading order, grouped by section — its route, its words and its claims.
// One home for what a page is CALLED and what it COVERS, so the nav, the page's own header, a section
// overview's leads and the coverage gates read one list. What a page SAYS is its `index.abide`.
//
// A section's first page is its OVERVIEW. `lead` is the page's first paragraph: `Doc` opens the page
// on it, and an overview shows it through `<Lead/>`, so it reads standalone and links by route (40.29).

export type SitePage = {
    route: string
    title: string
    nav: string
    intent: string
    lead: string
    /** The REGISTRY names a guide teaches (40.11). */
    covers?: readonly string[]
    /** Title and intent decided, prose not written. */
    stub?: boolean
    /**
     * 40.35, 40.36 — a teaching page with no card: what it teaches is done by a `command` run in a terminal,
     * or decided by the `deployment` an app is served from, and no component running on it can show it.
     */
    cardless?: 'command' | 'deployment'
}

